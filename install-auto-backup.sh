#!/usr/bin/env bash
# install-auto-backup.sh - set up "plug in the drive -> backup starts" on a headless Debian / Raspberry Pi OS
# Usage: sudo ./install-auto-backup.sh <backup-device> <source-dir> [repo-name] [--mount <path>] [--now]
set -euo pipefail

usage() {
  echo "Usage: sudo $0 <backup-device> <source-dir> [repo-name] [--mount <path>] [--now]"
  echo "  backup-device  partition holding the Borg repository, e.g. sdc2 or /dev/sdc2"
  echo "  source-dir     directory to back up, e.g. /disks/pp"
  echo "  repo-name      repository directory on the drive, default: borg-repo"
  echo "  --mount        mount point of the backup drive, default /mnt/backup"
  echo "  --now          start a backup right after installing"
  exit 1
}

DEV=""; SRC=""; REPO_NAME=""; MNT=/mnt/backup; RUN_NOW=0
while [[ $# -gt 0 ]]; do
  case $1 in
    --mount) MNT=${2:?missing mount point}; shift ;;
    --now)   RUN_NOW=1 ;;
    -h|--help) usage ;;
    -*) echo "Unknown option: $1"; usage ;;
    *)
      # Positional arguments: device, source directory, repository name
      if   [[ -z $DEV ]];       then DEV=$1
      elif [[ -z $SRC ]];       then SRC=$1
      elif [[ -z $REPO_NAME ]]; then REPO_NAME=$1
      else echo "Unexpected extra argument: $1"; usage
      fi
      ;;
  esac
  shift
done

[[ -n $DEV && -n $SRC ]] || usage
REPO_NAME=${REPO_NAME:-borg-repo}
[[ $DEV == /dev/* ]] || DEV=/dev/$DEV
SRC=${SRC%/}
[[ $EUID -eq 0 ]] || { echo "Please run with sudo."; exit 1; }
[[ -b $DEV ]] || { echo "Block device not found: $DEV"; exit 1; }
[[ -d $SRC ]] || { echo "Source directory not found: $SRC"; exit 1; }
if [[ $SRC =~ [[:space:]] || $MNT =~ [[:space:]] ]]; then
  echo "Paths containing spaces are not supported."; exit 1
fi
if [[ ! $REPO_NAME =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]]; then
  echo "Invalid repo name '$REPO_NAME'."; exit 1
fi

UUID=$(blkid -o value -s UUID "$DEV" || true)
[[ -n $UUID ]] || { echo "Could not read a filesystem UUID from $DEV."; exit 1; }

PASSFILE=/root/.config/borg/passphrase
[[ -s $PASSFILE ]] || { echo "Passphrase file $PASSFILE not found. Run borg-setup.sh first."; exit 1; }

echo "== Installing packages =="
command -v borg >/dev/null || apt-get install -y borgbackup
command -v borgmatic >/dev/null || { apt-get update && apt-get install -y borgmatic; }
BORGMATIC=$(command -v borgmatic)

# Mount the drive briefly to check that the repository really exists and the passphrase works
echo "== Checking the repository =="
TMP_MOUNTED=0
trap 'if [[ $TMP_MOUNTED -eq 1 ]]; then umount "$MNT" || true; fi' EXIT
if ! mountpoint -q "$MNT"; then
  mkdir -p "$MNT"
  mount "$DEV" "$MNT"
  TMP_MOUNTED=1
fi
[[ -d $MNT/$REPO_NAME ]] || { echo "No repository found at $MNT/$REPO_NAME"; exit 1; }
BORG_PASSCOMMAND="cat $PASSFILE" borg info "$MNT/$REPO_NAME" >/dev/null
echo "Repository OK: $MNT/$REPO_NAME"
# Unmount again right away so a backup started later does not lose its drive
if [[ $TMP_MOUNTED -eq 1 ]]; then umount "$MNT"; TMP_MOUNTED=0; fi

# Archive label comes from the source directory name
LABEL=$(basename "$SRC")
LABEL=${LABEL//[^A-Za-z0-9._-]/_}
LABEL=${LABEL:-root}

echo "== Writing borgmatic config =="
CONF=/etc/borgmatic.d/usb-backup.yaml
mkdir -p /etc/borgmatic.d
[[ -e $CONF ]] && cp -a "$CONF" "$CONF.bak-$(date +%s)"
cat > "$CONF" <<EOF
# Generated by install-auto-backup.sh
source_directories:
    - '${SRC//\'/\'\'}'
source_directories_must_exist: true

repositories:
    - path: '$MNT/$REPO_NAME'
      label: usb

archive_name_format: '{hostname}-$LABEL-{now:%Y-%m-%d_%H%M}'
compression: zstd,3
encryption_passcommand: cat $PASSFILE

exclude_patterns:
    - '*/lost+found'
    - '*/\$RECYCLE.BIN'
    - '*/System Volume Information'

keep_daily: 7
keep_weekly: 4
keep_monthly: 6
EOF
chmod 600 "$CONF"

echo "== Writing systemd service =="
# Only guard the source with a mount check if it is a separate mount right now
SRC_CHECK=""
if mountpoint -q "$SRC"; then
  SRC_CHECK="ExecStartPre=/bin/sh -c 'mountpoint -q $SRC'"
fi
cat > /etc/systemd/system/borgmatic-usb.service <<EOF
[Unit]
Description=borgmatic backup to USB drive

[Service]
Type=oneshot
# Mount the backup drive (unless it is already mounted) and check the source
ExecStartPre=/bin/sh -c 'mountpoint -q $MNT || mount /dev/disk/by-uuid/$UUID $MNT'
$SRC_CHECK
ExecStart=$BORGMATIC -c $CONF --verbosity 1 --stats
# Always flush and unmount afterwards, even if the backup failed, so the drive can be unplugged
ExecStopPost=-/bin/sh -c 'sync; umount $MNT'
# A first backup can take many hours
TimeoutStartSec=infinity
Nice=10
IOSchedulingClass=idle
EOF

echo "== Writing udev rule =="
cat > /etc/udev/rules.d/99-borgmatic-usb.rules <<EOF
# Start the backup when the drive with this filesystem UUID is plugged in
ACTION=="add", SUBSYSTEM=="block", ENV{ID_FS_UUID}=="$UUID", TAG+="systemd", ENV{SYSTEMD_WANTS}="borgmatic-usb.service"
EOF

systemctl daemon-reload
udevadm control --reload
"$BORGMATIC" config validate -c "$CONF"

echo
echo "== Done =="
echo "Backup drive: $DEV (UUID $UUID)"
echo "Source:       $SRC"
echo "Repository:   $MNT/$REPO_NAME"
echo "Config:       $CONF"
echo "Follow logs:  journalctl -u borgmatic-usb -f"
if [[ $RUN_NOW -eq 1 ]]; then
  systemctl start --no-block borgmatic-usb.service
  echo "A backup has been started now."
else
  echo "Unplug and re-plug the drive to start a backup, or run: sudo systemctl start borgmatic-usb"
fi
